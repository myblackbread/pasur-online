/**
 * Очередь последовательного исполнения асинхронных задач.
 * Гарантирует, что следующая задача стартует строго после завершения предыдущей,
 * даже если предыдущая завершилась с ошибкой.
 */
export class WriteQueue {
  private queue: Promise<void> = Promise.resolve();

  /**
   * Добавляет асинхронную задачу в хвост очереди.
   * [Алгоритмическое исключение]: принимает прямой коллбэк.
   *
   * @param task Функция, возвращающая промис
   * @returns Результат выполнения переданной задачи
   */
  enqueue<T>(task: () => Promise<T>): Promise<T> {
    const next = this.queue.then(() => task());
    this.queue = next.then(() => {}).catch(() => {});
    return next;
  }
}